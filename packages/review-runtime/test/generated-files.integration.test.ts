import { mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { revParse, runGit } from '@reviewbot/git-repository';
import { classifyNonReviewable, skipReasonByContent, skipReasonByPath } from '../src/generated-files.js';

describe('skipReasonByPath / skipReasonByContent', () => {
  it.each([
    ['lib/data/model/tab.g.dart', 'generated'],
    ['lib/virt/libvirt.freezed.dart', 'generated'],
    ['api/v1/service.pb.go', 'generated'],
    ['lib/generated/l10n/l10n.dart', 'generated'],
    ['pubspec.lock', 'generated'],
    ['sub/Cargo.lock', 'generated'],
    ['vendor/github.com/x/y.go', 'vendored'],
    ['web/third_party/lib.js', 'vendored'],
    ['lib/data/model/tab.dart', undefined],
    ['src/generator.ts', undefined],
    ['docs/generated.md', undefined],
  ])('%s → %s', (path, reason) => {
    expect(skipReasonByPath(path)).toBe(reason);
  });

  it('header markers only count near the top; NUL means binary', () => {
    expect(skipReasonByContent(Buffer.from('// GENERATED CODE - DO NOT MODIFY BY HAND\nclass A {}\n'))).toBe('generated');
    expect(skipReasonByContent(Buffer.from('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n'))).toBe('generated');
    expect(skipReasonByContent(Buffer.from('/** @generated */\n'))).toBe('generated');
    const late = `${'x\n'.repeat(10)}// Code generated by tool. DO NOT EDIT.\n`;
    expect(skipReasonByContent(Buffer.from(late))).toBeUndefined();
    expect(skipReasonByContent(Buffer.from('const s = "@generated tag parser";\n'))).toBeUndefined();
    expect(skipReasonByContent(Buffer.from([0x89, 0x50, 0x00, 0x01]))).toBe('binary');
    expect(skipReasonByContent(Buffer.from('export const a = 1;\n'))).toBeUndefined();
  });

  it('a Git LFS pointer is recognised by its whole format, not by its path or first line', () => {
    const pointer = `version https://git-lfs.github.com/spec/v1\noid sha256:${'c'.repeat(64)}\nsize 45912\n`;
    expect(skipReasonByContent(Buffer.from(pointer))).toBe('lfs-pointer');
    expect(skipReasonByContent(Buffer.from(`# ${pointer}`))).toBeUndefined();
    // Code appended after a pointer: not a pointer.
    expect(skipReasonByContent(Buffer.from(`${pointer}rm -rf "$HOME"\n`))).toBeUndefined();
    expect(skipReasonByContent(Buffer.from('version https://git-lfs.github.com/spec/v1\nsize 1\n'))).toBeUndefined();
  });
});

describe('classifyNonReviewable', () => {
  let dir: string;
  let baseSha: string;
  const outside = join(tmpdir(), `gen-outside-${Date.now()}`);

  const commit = async (message: string) => {
    await runGit(dir, ['add', '-A']);
    await runGit(dir, ['-c', 'user.email=t@example.com', '-c', 'user.name=T', 'commit', '-q', '-m', message]);
    return revParse(dir, 'HEAD');
  };

  beforeAll(async () => {
    dir = await mkdtemp(join(tmpdir(), 'gen-files-'));
    await runGit(dir, ['init', '-q', '-b', 'main']);
    await mkdir(join(dir, 'api'), { recursive: true });
    await mkdir(join(dir, 'src'), { recursive: true });
    await writeFile(
      join(dir, '.gitattributes'),
      'api/** linguist-generated\nsrc/keep.g.dart -linguist-generated\n',
    );
    await writeFile(join(dir, 'README.md'), 'base\n');
    baseSha = await commit('base');
    // The PR marks src/** as generated on head; only base attributes count.
    await writeFile(join(dir, '.gitattributes'), 'api/** linguist-generated\nsrc/** linguist-generated\n');
    await writeFile(join(dir, 'api', 'client.ts'), 'export const x = 1;\n');
    await writeFile(join(dir, 'src', 'app.ts'), 'export const y = 1;\n');
    await writeFile(join(dir, 'src', 'keep.g.dart'), 'class Keep {}\n');
    await writeFile(join(dir, 'src', 'gen.ts'), '// Code generated by tool. DO NOT EDIT.\nexport {};\n');
    await writeFile(join(dir, 'src', 'blob.bin'), Buffer.from([1, 0, 2]));
    // A symlink leaving the workspace is not read.
    await writeFile(outside, '// Code generated by tool. DO NOT EDIT.\n');
    await symlink(outside, join(dir, 'src', 'escape.ts'));
    await commit('head');
  });

  afterAll(async () => {
    await rm(dir, { recursive: true, force: true });
    await rm(outside, { force: true });
  });

  it('uses base .gitattributes, header markers and binary sniffing; ignores escaping symlinks', async () => {
    const reasons = await classifyNonReviewable({
      paths: ['api/client.ts', 'src/app.ts', 'src/keep.g.dart', 'src/gen.ts', 'src/blob.bin', 'src/escape.ts'],
      headDir: dir,
      gitDir: dir,
      baseSha,
    });
    expect(Object.fromEntries(reasons)).toEqual({
      'api/client.ts': 'generated',
      // `-linguist-generated` on base overrides the `*.g.dart` heuristic.
      'src/gen.ts': 'generated',
      'src/blob.bin': 'binary',
    });
  });

  it('without a workspace only path conventions apply', async () => {
    const reasons = await classifyNonReviewable({ paths: ['src/gen.ts', 'lib/a.g.dart'] });
    expect(Object.fromEntries(reasons)).toEqual({ 'lib/a.g.dart': 'generated' });
  });
});
